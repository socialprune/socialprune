const tokenMessages = new Map<string, (typeof tokenIds)[number]>(
  tokenIds.map((id) => [id.slice('desktop.token.'.length), id]),
);
export function tokenMessage(
  token:
    | RunStopDetail
    | RunEndReason
    | RunJournalOutcome
    | RunReadbackOutcome
    | RunAction
    | RunJournalCode
    | DesktopErrorCode,
) {
  const message = tokenMessages.get(token);
  if (!message) throw new Error('Missing desktop token message.');
  return message;
}

